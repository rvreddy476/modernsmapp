#!/usr/bin/env bash
# android-deps-lockfile.sh <out-lockfile>
#
# Writes the external components every Android application module ships in a
# release build (all flavours) as a Gradle lockfile, the format osv-scanner
# reads (`group:name:version=<configurations>`). Gate line 5, Android
# dependency scan (.github/workflows/android-native.yml, job dependency-scan).
#
# The project has no Gradle lockfiles or verification metadata, so the list
# comes from the resolved release runtime classpaths, through an init script
# (android-release-deps.init.gradle): no build file changes.
#
# Online by default (a CI runner has no Gradle cache); ANDROID_DEPS_OFFLINE=1
# resolves from the local Gradle cache only. Needs app/google-services.json
# only as much as Gradle configuration does (CI writes the placeholder).
set -euo pipefail

out="${1:?usage: android-deps-lockfile.sh <out-lockfile>}"
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"
android="$root/mobile/android"
case "$out" in /*|[A-Za-z]:*) ;; *) out="$PWD/$out" ;; esac

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

flags=(-q --no-configuration-cache -I "$here/android-release-deps.init.gradle" "-DciDepsOut=$tmp")
if [ "${ANDROID_DEPS_OFFLINE:-0}" = 1 ]; then flags+=(--offline); fi

(cd "$android" && ./gradlew "${flags[@]}" ciReleaseDependencies)

shopt -s nullglob
lists=("$tmp"/*.txt)
if [ ${#lists[@]} -eq 0 ]; then
  echo "FAIL android-deps: no application module wrote a dependency list" >&2
  exit 1
fi
for l in "${lists[@]}"; do
  printf '  %-22s %s components\n' "$(basename "$l" .txt)" "$(grep -c . "$l")"
done

{
  echo "# Generated by scripts/ci/android-deps-lockfile.sh: release runtime"
  echo "# classpaths of every Android application module. Not a real lockfile."
  sort -u "${lists[@]}" | grep . | sed 's/$/=releaseRuntimeClasspath/'
  echo "empty="
} >"$out"

n="$(grep -c '=releaseRuntimeClasspath$' "$out")"
if [ "$n" -eq 0 ]; then
  echo "FAIL android-deps: the dependency list is empty" >&2
  exit 1
fi
echo "PASS android-deps $n distinct components -> $out"
